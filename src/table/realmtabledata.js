import { Object } from "../../libs/vanilla.js/src/base/object.js";


//==============================================================================
// 경지 테이블 한 행의 데이터 구조체 (realmtable.json 의 각 객체에 대응).
// 수선자의 등급/수준을 나타낸다 (범인 < 연기기 < 결단기 < 원영기 < 화신기 ...).
// rank 가 작을수록 낮은 단계.
//==============================================================================
export class RealmTableData extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @type { number } */ id;
	/** @type { number } */ rank;
	/** @type { string } */ name;
	/** @type { string } */ description;

	//==============================================================================
	// 생성. data = realmtable.json 의 한 객체.
	//==============================================================================
	/**
	 * @param { Object } data
	 */
	constructor(data) {
		super();
		this.id = data.id;
		this.rank = typeof data.rank === "number" ? data.rank : 0;
		this.name = data.name || "";
		this.description = data.description || "";
	}
}
